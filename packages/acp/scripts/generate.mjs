#!/usr/bin/env node
// Generates zod schemas, TypeScript types and the bundled MCP tool definitions
// from the vendored ACP spec in ../spec/2026-04-17/. The output in
// ../src/generated/ is committed, so consumers never need this script.
//
// Usage: node scripts/generate.mjs [--check]
//   --check  exit 1 if the committed files differ from what would be generated

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const specDir = join(root, "spec/2026-04-17");
const outDir = join(root, "src/generated");

const HEADER =
  "// Generated by scripts/generate.mjs from spec/2026-04-17. Do not edit.\n";

const readJson = async (rel) =>
  JSON.parse(await readFile(join(specDir, rel), "utf8"));

// ---------------------------------------------------------------------------
// JSON Schema helpers

const DEF_PREFIX = "#/$defs/";

function refName(ref) {
  const i = ref.indexOf(DEF_PREFIX);
  if (i === -1) throw new Error(`Unsupported $ref: ${ref}`);
  return ref.slice(i + DEF_PREFIX.length);
}

function isConditional(node) {
  return node && typeof node === "object" && "if" in node && "then" in node;
}

/**
 * Merges `allOf` members that are objects into one object schema, the way the
 * spec intends `CheckoutSessionWithOrder` (base + order) to be read. A literal
 * JSON Schema reading would reject `order`, because the base is closed with
 * `additionalProperties: false`. `if`/`then` members are kept as conditionals.
 */
function mergeAllOf(node, resolve) {
  const { allOf, ...rest } = node;
  const merged = { ...rest };
  const conditionals = [];
  let closed = rest.additionalProperties === false;
  for (const member of allOf) {
    if (isConditional(member)) {
      conditionals.push(member);
      continue;
    }
    let m = member.$ref ? resolve(member.$ref) : member;
    if (m.allOf) m = mergeAllOf(m, resolve);
    if (m.type !== "object" && !m.properties) {
      throw new Error(`Unsupported allOf member: ${JSON.stringify(member)}`);
    }
    merged.type = "object";
    merged.properties = { ...merged.properties, ...m.properties };
    merged.required = [
      ...new Set([...(merged.required ?? []), ...(m.required ?? [])]),
    ];
    if (m.additionalProperties === false) closed = true;
    if (m["x-conditionals"]) conditionals.push(...m["x-conditionals"]);
    if (!merged.description && m.description)
      merged.description = m.description;
    if (m.anyOf) merged.anyOf = m.anyOf;
  }
  if (closed) merged.additionalProperties = false;
  if (merged.required?.length === 0) delete merged.required;
  if (conditionals.length) merged["x-conditionals"] = conditionals;
  return merged;
}

const isRequiredOnlyAnyOf = (anyOf) =>
  anyOf.every((m) => Object.keys(m).length === 1 && Array.isArray(m.required));

// ---------------------------------------------------------------------------
// zod emitter

function createEmitter(defs, nameOf) {
  const resolve = (ref) => defs[refName(ref)];

  function emit(node) {
    if (node.$ref) return `${nameOf(refName(node.$ref))}Schema`;
    if (node.allOf) return emit(mergeAllOf(node, resolve));

    let code;
    if (node.oneOf && !node.type) {
      code = `z.union([${node.oneOf.map(emit).join(", ")}])`;
    } else if (node.anyOf && !node.type && !isRequiredOnlyAnyOf(node.anyOf)) {
      code = `z.union([${node.anyOf.map(emit).join(", ")}])`;
    } else if ("const" in node) {
      code = `z.literal(${JSON.stringify(node.const)})`;
    } else if (node.enum) {
      code = node.enum.every((v) => typeof v === "string")
        ? `z.enum(${JSON.stringify(node.enum)})`
        : `z.union([${node.enum.map((v) => `z.literal(${JSON.stringify(v)})`).join(", ")}])`;
    } else if (Array.isArray(node.type)) {
      code = `z.union([${node.type.map((t) => emit({ ...node, type: t })).join(", ")}])`;
    } else {
      switch (node.type) {
        case "string":
          code = emitString(node);
          break;
        case "integer":
        case "number":
          code = node.type === "integer" ? "z.int()" : "z.number()";
          if (node.minimum !== undefined) code += `.min(${node.minimum})`;
          if (node.maximum !== undefined) code += `.max(${node.maximum})`;
          break;
        case "boolean":
          code = "z.boolean()";
          break;
        case "array":
          code = `z.array(${node.items ? emit(node.items) : "z.unknown()"})`;
          if (node.minItems !== undefined) code += `.min(${node.minItems})`;
          if (node.maxItems !== undefined) code += `.max(${node.maxItems})`;
          if (node.uniqueItems) code += ".refine(uniqueItems, UNIQUE_ITEMS)";
          break;
        case "object":
        case undefined:
          code = emitObject(node);
          break;
        default:
          throw new Error(`Unsupported type: ${node.type}`);
      }
    }
    return code;
  }

  function emitString(node) {
    let code;
    if (node.format === "date-time") code = "z.iso.datetime({ offset: true })";
    else if (node.format === "uri") code = "z.url()";
    else if (node.format === "email") code = "z.email()";
    else if (node.format) throw new Error(`Unsupported format: ${node.format}`);
    else code = "z.string()";
    if (node.minLength !== undefined) code += `.min(${node.minLength})`;
    if (node.maxLength !== undefined) code += `.max(${node.maxLength})`;
    if (node.pattern)
      code += `.regex(new RegExp(${JSON.stringify(node.pattern)}))`;
    return code;
  }

  function emitObject(node) {
    const props = node.properties ?? {};
    const required = new Set(node.required ?? []);
    const ap = node.additionalProperties;
    let code;
    if (Object.keys(props).length === 0) {
      code =
        ap && typeof ap === "object"
          ? `z.record(z.string(), ${emit(ap)})`
          : "z.record(z.string(), z.unknown())";
    } else {
      const shape = Object.entries(props)
        .map(([key, value]) => {
          const doc = value.description ? jsdoc(value.description) : "";
          const opt = required.has(key) ? "" : ".optional()";
          return `${doc}${JSON.stringify(key)}: ${emit(value)}${opt},`;
        })
        .join("\n");
      if (ap === false) code = `z.strictObject({\n${shape}\n})`;
      else if (ap && typeof ap === "object")
        code = `z.object({\n${shape}\n}).catchall(${emit(ap)})`;
      else code = `z.looseObject({\n${shape}\n})`;
    }
    if (node.anyOf && isRequiredOnlyAnyOf(node.anyOf)) {
      const groups = JSON.stringify(node.anyOf.map((m) => m.required));
      code += `.superRefine(requireOneGroup(${groups}))`;
    }
    for (const cond of node["x-conditionals"] ?? []) {
      code += `.superRefine(requireWhen(${JSON.stringify(conditionSpec(cond))}))`;
    }
    return code;
  }

  return emit;
}

/** Supports `if: { properties: { k: { enum | const } } }, then: { required }`. */
function conditionSpec({ if: cond, then }) {
  const when = {};
  for (const [key, value] of Object.entries(cond.properties ?? {})) {
    if (value.enum) when[key] = value.enum;
    else if ("const" in value) when[key] = [value.const];
    else throw new Error(`Unsupported if: ${JSON.stringify(cond)}`);
  }
  if (!then.required || Object.keys(then).length !== 1) {
    throw new Error(`Unsupported then: ${JSON.stringify(then)}`);
  }
  return { when, required: then.required };
}

function jsdoc(text) {
  const body = text.replaceAll("*/", "*\\/").split("\n").join("\n * ");
  return `/** ${body} */\n`;
}

/** Orders definitions so every schema is declared after the ones it uses. */
function topoSort(defs) {
  const order = [];
  const seen = new Set();
  const visit = (name, stack = []) => {
    if (seen.has(name)) return;
    if (stack.includes(name)) {
      throw new Error(`Recursive schema ${[...stack, name].join(" -> ")}`);
    }
    const deps = new Set();
    JSON.stringify(defs[name], (key, value) => {
      if (key === "$ref") deps.add(refName(value));
      return value;
    });
    for (const dep of deps) visit(dep, [...stack, name]);
    seen.add(name);
    order.push(name);
  };
  for (const name of Object.keys(defs)) visit(name);
  return order;
}

function generateSchemas(bundle, { title, rename = {} }) {
  const defs = bundle.$defs;
  const nameOf = (name) => rename[name] ?? name;
  const emit = createEmitter(defs, nameOf);
  const parts = [];
  for (const name of topoSort(defs)) {
    const def = defs[name];
    const exported = nameOf(name);
    const doc = def.description ? jsdoc(def.description) : "";
    parts.push(`${doc}export const ${exported}Schema = ${emit(def)};`);
    parts.push(
      `${doc}export type ${exported} = z.infer<typeof ${exported}Schema>;\n`,
    );
  }
  const body = parts.join("\n");
  const helpers = [
    "requireOneGroup",
    "requireWhen",
    "uniqueItems",
    "UNIQUE_ITEMS",
  ].filter((helper) => new RegExp(`\\b${helper}\\b`).test(body));
  return [
    HEADER,
    `// ${title}\n`,
    'import { z } from "zod";',
    helpers.length
      ? `import { ${helpers.join(", ")} } from "../runtime.ts";\n`
      : "",
    body,
  ].join("\n");
}

// ---------------------------------------------------------------------------
// MCP tools: OpenRPC methods with every $ref inlined

function createBundler(documents) {
  // documents: { [fileKey]: json }, refs look like "file#/pointer" or "#/pointer"
  function lookup(file, pointer) {
    let node = documents[file];
    for (const part of pointer.split("/").filter(Boolean)) {
      node = node[part.replaceAll("~1", "/").replaceAll("~0", "~")];
      if (node === undefined) throw new Error(`Unresolved ${file}#${pointer}`);
    }
    return { node, file };
  }

  function resolveRef(ref, file) {
    const [path, pointer = ""] = ref.split("#");
    const target = path ? path.split("/").pop() : file;
    return lookup(target, pointer);
  }

  function inline(node, file) {
    if (Array.isArray(node)) return node.map((n) => inline(n, file));
    if (!node || typeof node !== "object") return node;
    if (node.$ref) {
      const { $ref, ...siblings } = node;
      const target = resolveRef($ref, file);
      return { ...inline(target.node, target.file), ...inline(siblings, file) };
    }
    if (node.allOf && !node.allOf.some(isConditional)) {
      const members = node.allOf.map((m) => inline(m, file));
      return inline(
        mergeAllOf({ ...node, allOf: members }, () => {}),
        file,
      );
    }
    const out = {};
    for (const [key, value] of Object.entries(node)) {
      if (key === "example" || key === "$schema" || key === "$id") continue;
      out[key] =
        key === "properties" ? mapValues(value, file) : inline(value, file);
    }
    return out;
  }

  const mapValues = (obj, file) =>
    Object.fromEntries(
      Object.entries(obj).map(([k, v]) => [k, inline(v, file)]),
    );

  return (node, file) => inline(node, file);
}

function generateTools(openrpc, checkout) {
  const bundle = createBundler({
    "openrpc.agentic_checkout.json": openrpc,
    "schema.agentic_checkout.json": checkout,
  });
  const file = "openrpc.agentic_checkout.json";
  const tools = openrpc.methods.map((method) => {
    const properties = {};
    const required = [];
    for (const param of method.params) {
      const schema = bundle(param.schema, file);
      properties[param.name] = param.description
        ? { ...schema, description: param.description }
        : schema;
      if (param.required) required.push(param.name);
    }
    return {
      name: method.name,
      title: method.summary,
      description: method.description,
      // No outputSchema: the inlined CheckoutSession is ~60 KB per tool and
      // would dominate tools/list. Results are validated with the zod schemas.
      inputSchema: { type: "object", properties, required },
    };
  });
  return [
    HEADER,
    'import type { McpToolDefinition } from "../types.ts";\n',
    "/** The five ACP checkout tools from the MCP binding, with every $ref inlined. */",
    `export const mcpTools: readonly McpToolDefinition[] = ${JSON.stringify(tools)};`,
  ].join("\n");
}

// ---------------------------------------------------------------------------

export async function generate() {
  const checkout = await readJson("json-schema/schema.agentic_checkout.json");
  const delegate = await readJson("json-schema/schema.delegate_payment.json");
  const openrpc = await readJson("openrpc/openrpc.agentic_checkout.json");
  const files = {
    "checkout.ts": generateSchemas(checkout, { title: checkout.title }),
    "delegate-payment.ts": generateSchemas(delegate, {
      title: delegate.title,
      // Avoid clashing with the checkout bundle's Address and Error.
      rename: {
        Address: "DelegatePaymentAddress",
        Error: "DelegatePaymentError",
      },
    }),
    "mcp-tools.ts": generateTools(openrpc, checkout),
  };
  const out = {};
  for (const [name, source] of Object.entries(files)) {
    const filepath = join(outDir, name);
    const options = (await prettier.resolveConfig(filepath)) ?? {};
    out[filepath] = await prettier.format(source, { ...options, filepath });
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const files = await generate();
  let stale = false;
  for (const [filepath, content] of Object.entries(files)) {
    if (check) {
      const current = await readFile(filepath, "utf8").catch(() => "");
      if (current !== content) {
        console.error(`stale: ${filepath}`);
        stale = true;
      }
    } else {
      await writeFile(filepath, content);
      console.log(`wrote ${filepath}`);
    }
  }
  if (stale) process.exit(1);
}
